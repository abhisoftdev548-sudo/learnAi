import { Router } from 'express';
import auth from './authRoutes.js';
import challenges from './challengeRoutes.js';
import submissions from './submissionRoutes.js';
import users from './userRoutes.js';
import admin from './adminRoutes.js';
import { authenticate } from '../middleware/auth.js';
import { validate, leaderboardQuery } from '../utils/validation.js';
import { ranking, achievements } from '../controllers/userController.js';
import { myTeam } from '../controllers/adminController.js';
const router = Router();
router.use('/auth', auth);
router.use('/challenges', challenges);
router.use('/submissions', submissions);
router.use('/users', users);
router.use('/admin', admin);
router.get('/achievements', authenticate, achievements);
router.get('/leaderboard', authenticate, validate(leaderboardQuery, 'query'), ranking);
router.get('/teams/me', authenticate, myTeam);
export default router;
