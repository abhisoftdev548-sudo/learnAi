import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { randomUUID } from 'node:crypto';
import mongoose from 'mongoose';
import { env, origins } from './config/env.js';
import routes from './routes/index.js';
import { checkOrigin } from './middleware/auth.js';
import { errorHandler } from './middleware/error.js';
import { ApiError, ok } from './utils/http.js';
const app = express();
app.disable('x-powered-by');
app.set('trust proxy', env.TRUST_PROXY);
app.use((req, res, next) => { req.id = randomUUID(); res.setHeader('X-Request-Id', req.id); res.setHeader('Cache-Control', 'no-store'); next(); });
app.use(helmet());
app.use(cors({ origin(origin, callback) { callback(origin && !origins.includes(origin) ? new ApiError(403, 'Origin not allowed') : null, true); }, credentials: true, methods: ['GET', 'POST', 'PUT', 'DELETE', 'OPTIONS'], allowedHeaders: ['Content-Type'] }));
app.get('/health/live', (req, res) => ok(res, { status: 'alive' }));
app.get('/health/ready', (req, res) => mongoose.connection.readyState === 1 ? ok(res, { status: 'ready' }) : res.status(503).json({ success: false, message: 'Database unavailable' }));
app.use('/api', rateLimit({ windowMs: 60000, limit: 120, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many requests' } }));
app.use(checkOrigin);
app.use(express.json({ limit: '200kb', strict: true }));
app.use(cookieParser());
app.use('/api', routes);
app.use((req, res, next) => next(new ApiError(404, 'Route not found')));
app.use(errorHandler);
export default app;
